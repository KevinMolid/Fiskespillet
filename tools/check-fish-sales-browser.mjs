// Real GamePage, inventory and shop UI; offline fixture services only.
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href)
const browser = await chromium.launch({ headless: true, channel: 'msedge' })
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:5181'
await mkdir('output/fish-sales-review', { recursive: true })
try {
  for (const [mode, width, height] of [['desktop',1280,900],['mobile',390,844],['narrow',320,740],['landscape',844,390]]) {
    const mobile = mode !== 'desktop'
    const context = await browser.newContext({ viewport:{width,height}, deviceScaleFactor:mobile?3:1, isMobile:mobile, hasTouch:mobile })
    const page = await context.newPage(), errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.routeWebSocket(/^ws:\/\/127\.0\.0\.1:/, () => {})
    await page.route(/\/src\/game\/WorldScene\.ts(?:\?.*)?$/, async route => {
      const response = await route.fetch()
      await route.fulfill({ response, body:(await response.text()).replace('return { game, scene };','window.__economyWorld=scene; return { game, scene };') })
    })
    await page.route(/\/src\/game\/GamePage\.tsx(?:\?.*)?$/, async route => {
      const response = await route.fetch()
      const body = (await response.text()).replace('const canFishNow =', 'window.__finishFish=finishFishingSession; const canFishNow =')
      assert(body.includes('__finishFish')); await route.fulfill({response,body})
    })
    await page.route(/\/tools\/game-preview\.tsx(?:\?.*)?$/, async route => {
      const response = await route.fetch()
      let body = (await response.text()).replace('equippedBait: "bread"','equippedBait: "spinner"')
        .replace('spinner: 1','spinner: 20')
        .replace('sellFish: async (_uid, id, amount) => {','sellFish: async (_uid, id, amount) => { window.__saleCalls=(window.__saleCalls||0)+1; if(window.__saleGate) await window.__saleGate; if(window.__rejectSale) throw new Error("Salget kunne ikke lagres.");')
      assert(body.includes('__saleGate'))
      body += '\nwindow.__economy={read:snapshot,book:()=>structuredClone(fishBook)}; inventory.bag.fish_torsk=2; inventory.bag.fish_mort=1; inventory.bag.fish_orret=1;\n'
      await route.fulfill({response,body})
    })
    await page.goto(`${base}/tools/game-preview.html`)
    await page.waitForFunction(() => window.__economyWorld?.playerImage)
    const read = () => page.evaluate(() => window.__economy.read())
    const menu = async () => mobile ? page.getByRole('button',{name:'Meny',exact:true}).click() : page.keyboard.press('Enter')
    const back = async () => mobile ? page.getByRole('button',{name:'B: tilbake',exact:true}).click() : page.keyboard.press('b')
    const go = async name => {
      await page.getByText('Teststeder og posisjon',{exact:true}).click()
      await page.getByRole('button',{name,exact:true}).click()
      await page.waitForFunction(() => window.__economyWorld?.playerImage)
      await page.getByText('Teststeder og posisjon',{exact:true}).click()
      await page.locator('.game-frame').focus()
    }
    const act = async () => mobile ? page.locator('.pocket-action').click() : page.keyboard.press('e')
    await go('Fiske ved bryggen')
    for (let index=0; index<2; index++) {
      await act(); await page.getByRole('dialog',{name:'Kastelengde'}).waitFor()
      await page.evaluate(async () => {
        const { FISH_BY_ID } = await import('/src/game/fish.ts')
        await window.__finishFish({type:'landed',species:FISH_BY_ID.makrell,grams:1000,bait:'spinner'})
      })
      assert.equal((await read()).coins,60,'Catching fish grants no coins')
      assert.equal((await read()).bag.fish_makrell,index+1)
      assert(!(await page.locator('.game-frame').innerText()).includes('mynter'),'Catch output has no coin reward')
      assert((await page.locator('.game-frame').innerText()).includes('sekken'))
      await page.getByRole('button',{name:/^Videre/}).first().click()
    }
    for (const reason of ['no-bite','missed-hook','line-broken','bottom-snag']) {
      await act(); await page.getByRole('dialog',{name:'Kastelengde'}).waitFor()
      await page.evaluate(async reason => window.__finishFish({type:'escaped',reason,bait:'spinner'}),reason)
      const text = await page.locator('.world-message').innerText()
      assert(!/agnet|sluk|brukt/i.test(text),'Failure messages do not announce bait loss')
      assert.equal((await read()).bag.fish_makrell,2)
      assert.equal((await read()).coins,60)
      await page.getByRole('button',{name:/^Videre/}).first().click()
    }
    await menu(); await page.getByRole('button',{name:/Sekk/}).click()
    const bag = page.getByRole('dialog',{name:'Sekken'})
    await bag.getByRole('tab',{name:'Fisk',exact:true}).click()
    await bag.getByRole('heading',{name:/Makrell ×2/}).waitFor()
    assert.equal(await bag.getByRole('button',{name:'Velg agn'}).count(),0,'Fish are not bait')
    await bag.getByRole('button',{name:'Neste side'}).click()
    assert((await bag.innerText()).includes('Ørret') && (await bag.innerText()).includes('Mort'),'Fish category paginates')
    await page.screenshot({path:`output/fish-sales-review/bag-${mode}.png`,fullPage:true})
    await back(); await menu()
    await go('Ved butikkdisken'); await act()
    const shop = page.getByRole('dialog',{name:'Agnbutikken'})
    await shop.getByRole('tab',{name:'Selg fisk'}).click()
    const makrell = shop.locator('article').filter({hasText:'Makrell'})
    await makrell.getByRole('button',{name:'Selg 1',exact:true}).click()
    assert.equal((await read()).coins,68); assert.equal((await read()).bag.fish_makrell,1)
    assert((await makrell.innerText()).includes('×1'))
    const journal = await page.evaluate(() => JSON.stringify(window.__economy.book()))
    await page.evaluate(() => { window.__saleGate=new Promise(resolve=>window.__releaseSale=resolve) })
    await makrell.getByRole('button',{name:'Selg 1',exact:true}).click()
    assert(await shop.getByRole('tab',{name:'Kjøp agn'}).isDisabled())
    assert(await makrell.getByRole('button',{name:'Selg 1',exact:true}).isDisabled())
    assert(await page.locator('.pocket-menu').isDisabled())
    await page.keyboard.press('b'); await shop.waitFor()
    await page.evaluate(() => { window.__releaseSale(); window.__saleGate=null })
    await makrell.waitFor({state:'hidden'})
    assert.equal((await read()).coins,76); assert.equal((await read()).bag.fish_makrell,undefined)
    const torsk = shop.locator('article').filter({hasText:'Torsk'})
    const beforeFailure = await read()
    await page.evaluate(() => {window.__rejectSale=true})
    await torsk.getByRole('button',{name:'Selg alle (2)'}).click()
    await shop.getByRole('alert').waitFor()
    assert.deepEqual(await read(),beforeFailure,'A failed sale retains fish and coins')
    await page.evaluate(() => {window.__rejectSale=false})
    await torsk.getByRole('button',{name:'Selg alle (2)'}).click()
    await torsk.waitFor({state:'hidden'})
    assert.equal((await read()).coins,100)
    assert.equal(await page.evaluate(() => JSON.stringify(window.__economy.book())),journal,'Selling leaves catch records intact')
    await page.screenshot({path:`output/fish-sales-review/shop-${mode}.png`,fullPage:true})
    for (const name of ['Ørret','Mort']) await shop.locator('article').filter({hasText:name}).getByRole('button',{name:'Selg 1',exact:true}).click()
    await shop.getByText(/Ingen fisk i sekken/).waitFor()
    await shop.getByRole('tab',{name:'Kjøp agn'}).click()
    const worm = shop.locator('article').filter({hasText:'Mark'})
    await worm.getByRole('button',{name:'Kjøp 1',exact:true}).click()
    assert.equal((await read()).coins,114,'Fish sale proceeds buy existing bait')
    await back(); assert.equal(await shop.count(),0,'B still returns from the shop')
    assert(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth))
    assert.deepEqual(errors,[])
    await context.close()
    console.log(`${mode}: catch stacks/no coins, all failure messages, bag pagination, single/all sales, pending/failed writes, journal preservation and bait purchases passed.`)
  }
} finally { await browser.close() }
